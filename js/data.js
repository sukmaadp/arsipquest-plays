/**
 * Normalizes and looks up a site by slug or ID.
 */
function findSiteBySlug(rawSlug) {
  if (!rawSlug || typeof rawSlug !== "string") return null;

  let clean = rawSlug.trim().toLowerCase();
  clean = clean.split("?")[0].split("#")[0];
  clean = clean.replace(/\.html$/i, "");
  clean = clean.replace(/^[/\\]+|[/\\]+$/g, "");
  clean = clean.replace(/-/g, "_");

  // Direct ID match or alias match (with or without situs_ prefix)
  return SITES_DATA.find(s => 
    s.id === clean || 
    s.id === "situs_" + clean || 
    s.id.replace(/^situs_/, "") === clean
  ) || null;
}

// Attach globally
if (typeof window !== "undefined") {
  window.SITES_DATA = SITES_DATA;
  window.findSiteBySlug = findSiteBySlug;
}
if (typeof module !== "undefined" && module.exports) {
  module.exports = { SITES_DATA, findSiteBySlug };
}
